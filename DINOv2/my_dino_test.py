"""Multi-label evaluation of DINOv2 models on chest X-rays stored as NPZ files.

This script evaluates checkpoints generated by the corresponding training
scripts, whose model architecture consists of:

    DINOv2 encoder -> Dropout -> Linear multi-label classifier

Main features:
- automatically reconstructs the DINOv2 variant specified in the checkpoint;
- loads the full encoder and classifier state;
- applies the same preprocessing used during training validation;
- runs inference on the test set;
- computes overall and per-class metrics;
- saves predictions, metrics, and metadata to CSV/JSON files.

PyTorch Hub notes:
- the checkpoint already contains all trained weights, so the encoder is
  initialized with pretrained=False;
- the DINOv2 repository code must still be available in the PyTorch Hub cache
  or accessible over the internet;
- alternatively, use --hub-source local and --dinov2-repo to specify a local
  copy of the facebookresearch/dinov2 repository.
"""

