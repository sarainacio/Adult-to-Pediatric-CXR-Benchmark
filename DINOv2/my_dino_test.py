def load_checkpoint(
    checkpoint_path: Path,
    device: torch.device,
) -> dict[str, Any]:
    if not checkpoint_path.exists():
        raise FileNotFoundError(
            f"The checkpoint does not exist:\n{checkpoint_path}"
        )

    try:
        checkpoint = torch.load(
            checkpoint_path,
            map_location=device,
            weights_only=False,
        )
    except TypeError:
        checkpoint = torch.load(
            checkpoint_path,
            map_location=device,
        )

    if not isinstance(checkpoint, dict):
        raise TypeError(
            "The checkpoint must be a dictionary or a state_dict."
        )

    return checkpoint


def extract_model_state_dict(checkpoint: dict[str, Any]) -> dict[str, torch.Tensor]:
    """Extract model weights from common checkpoint formats."""

    for key in ("model_state_dict", "state_dict", "model"):
        candidate = checkpoint.get(key)
        if isinstance(candidate, dict) and candidate:
            state_dict = candidate
            break
    else:
        if checkpoint and all(
            isinstance(value, torch.Tensor)
            for value in checkpoint.values()
        ):
            state_dict = checkpoint
        else:
            raise KeyError(
                "No state_dict was found. Expected the keys "
                "'model_state_dict', 'state_dict' ou 'model'."
            )

    cleaned: dict[str, torch.Tensor] = {}

    for original_key, value in state_dict.items():
        key = str(original_key)

        # Support for DataParallel and training wrappers.
        changed = True
        while changed:
            changed = False
            for prefix in ("module.", "model."):
                if key.startswith(prefix):
                    key = key[len(prefix):]
                    changed = True

        cleaned[key] = value

    return cleaned


def load_dinov2_encoder(
    repository: str,
    model_name: str,
    hub_source: str,
    trust_repo: bool,
    force_reload: bool,
) -> nn.Module:
    """Instantiate the DINOv2 architecture without external pretrained weights."""

    kwargs: dict[str, Any] = {
        "repo_or_dir": repository,
        "model": model_name,
        "source": hub_source,
        "pretrained": LOAD_ORIGINAL_PRETRAINED_WEIGHTS,
        "force_reload": force_reload,
    }

    if hub_source == "github":
        kwargs["trust_repo"] = trust_repo

    try:
        encoder = torch.hub.load(**kwargs)
    except TypeError:
        # Compatibility with older PyTorch versions without trust_repo.
        kwargs.pop("trust_repo", None)
        encoder = torch.hub.load(**kwargs)
    except Exception as error:
        source_hint = (
            "Check the internet connection or the PyTorch Hub cache."
            if hub_source == "github"
            else "Check that --dinov2-repo points to the local repository."
        )
        raise RuntimeError(
            f"Could not instantiate {model_name!r} using PyTorch Hub. "
            f"{source_hint}"
        ) from error

    if not hasattr(encoder, "embed_dim"):
        raise AttributeError(
            "The loaded DINOv2 encoder does not have the attribute 'embed_dim'."
        )

    return encoder


class DINOv2Classifier(nn.Module):
    """The same model wrapper used in the training script."""

    def __init__(
        self,
        encoder: nn.Module,
        num_classes: int,
        dropout: float = 0.0,
    ):
        super().__init__()
        self.encoder = encoder
        self.classifier = nn.Sequential(
            nn.Dropout(p=dropout),
            nn.Linear(int(encoder.embed_dim), num_classes),
        )

    def forward(self, images: torch.Tensor) -> torch.Tensor:
        features = self.encoder(images)

        if not isinstance(features, torch.Tensor):
            raise TypeError(
                "The DINOv2 forward pass should return a tensor, but returned "
                f"{type(features).__name__}."
            )

        if features.ndim != 2:
            raise ValueError(
                "Expected an embedding [batch, dimension], but received "
                f"shape={tuple(features.shape)}."
            )

        return self.classifier(features)


def resolve_metadata(
    checkpoint: dict[str, Any],
    args: argparse.Namespace,
) -> dict[str, Any]:
    """Combine command-line arguments, checkpoint metadata, and fallback values."""

    label_columns = checkpoint.get("label_columns", DEFAULT_LABEL_COLUMNS)
    if not isinstance(label_columns, (list, tuple)) or not label_columns:
        raise ValueError("'label_columns' in the checkpoint is invalid.")

    label_columns = [str(label) for label in label_columns]

    image_size = int(checkpoint.get("image_size", DEFAULT_IMAGE_SIZE))
    if image_size <= 0:
        raise ValueError("The image_size specified in the checkpoint is invalid.")

    in_chans = int(checkpoint.get("in_chans", 3))
    if in_chans != 3:
        raise ValueError(
            "This script repeats the grayscale channel as RGB, but the checkpoint "
            f"indica in_chans={in_chans}."
        )

    checkpoint_key = checkpoint.get(
        "npz_image_key",
        DEFAULT_NPZ_IMAGE_KEY,
    )
    image_key = (
        args.npz_image_key
        if args.npz_image_key is not None
        else checkpoint_key
    )

    checkpoint_min_max = bool(
        checkpoint.get(
            "apply_min_max_normalization",
            DEFAULT_APPLY_MIN_MAX_NORMALIZATION,
        )
    )
    apply_min_max_normalization = (
        args.apply_min_max_normalization
        if args.apply_min_max_normalization is not None
        else checkpoint_min_max
    )

    imagenet_mean = checkpoint.get("imagenet_mean", DEFAULT_IMAGENET_MEAN)
    imagenet_std = checkpoint.get("imagenet_std", DEFAULT_IMAGENET_STD)

    imagenet_mean = [float(value) for value in imagenet_mean]
    imagenet_std = [float(value) for value in imagenet_std]

    if len(imagenet_mean) != 3 or len(imagenet_std) != 3:
        raise ValueError(
            "imagenet_mean and imagenet_std must have exactly three values."
        )

    if any(value <= 0 for value in imagenet_std):
        raise ValueError("All imagenet_std values must be positive.")

    # Use a default evaluation threshold of 0.5 for direct comparison across
    # architectures. Override it only when --threshold is explicitly supplied.
    threshold = (
        float(args.threshold)
        if args.threshold is not None
        else DEFAULT_THRESHOLD
    )

    if not 0.0 < threshold < 1.0:
        raise ValueError("The threshold must be strictly between 0 and 1.")

    checkpoint_repository = str(
        checkpoint.get(
            "dinov2_hub_repository",
            DEFAULT_DINOV2_HUB_REPOSITORY,
        )
    )

    repository = (
        str(args.dinov2_repo)
        if args.dinov2_repo is not None
        else checkpoint_repository
    )

    hub_source = args.hub_source
    if hub_source == "local" and not Path(repository).exists():
        raise FileNotFoundError(
            "With --hub-source local, --dinov2-repo must point to an "
            f"existing directory. Received value: {repository}"
        )

    model_name = str(
        checkpoint.get("model_name", DEFAULT_MODEL_NAME)
    )

    return {
        "model_name": model_name,
        "dinov2_hub_repository": repository,
        "hub_source": hub_source,
        "label_columns": label_columns,
        "num_classes": len(label_columns),
        "image_size": image_size,
        "in_chans": in_chans,
        "input_format": checkpoint.get("input_format", "npz"),
        "npz_image_key": image_key,
        "apply_min_max_normalization": apply_min_max_normalization,
        "imagenet_mean": imagenet_mean,
        "imagenet_std": imagenet_std,
        "classification_threshold": threshold,
        "checkpoint_threshold": checkpoint.get("threshold"),
        "epoch": checkpoint.get("epoch"),
        "protocol": checkpoint.get(
            "protocol",
            checkpoint.get("fine_tuning", "unknown"),
        ),
        "validation_loss": checkpoint.get("validation_loss"),
        "validation_metrics": checkpoint.get("validation_metrics"),
        "best_validation_macro_auc": checkpoint.get(
            "best_validation_macro_auc"
        ),
        "model_selection_metric": checkpoint.get("model_selection_metric"),
    }


def build_model_from_checkpoint(
    checkpoint: dict[str, Any],
    metadata: dict[str, Any],
    device: torch.device,
    trust_repo: bool,
    force_reload: bool,
) -> nn.Module:
    encoder = load_dinov2_encoder(
        repository=metadata["dinov2_hub_repository"],
        model_name=metadata["model_name"],
        hub_source=metadata["hub_source"],
        trust_repo=trust_repo,
        force_reload=force_reload,
    )

    model = DINOv2Classifier(
        encoder=encoder,
        num_classes=metadata["num_classes"],
        dropout=0.0,
    )

    state_dict = extract_model_state_dict(checkpoint)

    try:
        incompatible = model.load_state_dict(state_dict, strict=True)
    except RuntimeError as error:
        state_dict_keys = list(state_dict.keys())
        examples = state_dict_keys[:10]
        raise RuntimeError(
            "The checkpoint is incompatible with the expected DINOv2 wrapper. "
            "The provided training script uses the keys 'encoder.*' e "
            "'classifier.1.*'. Examples of keys found: "
            f"{examples}"
        ) from error

    if incompatible.missing_keys or incompatible.unexpected_keys:
        raise RuntimeError(
            "Checkpoint loading incompatibility. "
            f"Missing keys: {incompatible.missing_keys} | "
            f"Unexpected keys: {incompatible.unexpected_keys}"
        )

    model = model.to(device)
    model.eval()
    return model


