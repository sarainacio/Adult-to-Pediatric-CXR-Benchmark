def load_npz_image_array(
    image_path: Path,
    image_key: str | None,
) -> np.ndarray:
    """Read the image array from an NPZ file."""

    preferred_keys = (
        "image",
        "arr_0",
        "pixel_array",
        "pixels",
        "data",
    )

    try:
        with np.load(image_path, allow_pickle=False) as archive:
            available_keys = list(archive.files)

            if not available_keys:
                raise ValueError(
                    f"The NPZ file contains no arrays:\n{image_path}"
                )

            if image_key is not None:
                selected_key = str(image_key)
                if selected_key not in archive:
                    raise KeyError(
                        f"The NPZ key {selected_key!r} does not exist in "
                        f"{image_path}. Available keys: {available_keys}."
                    )
            else:
                selected_key = next(
                    (key for key in preferred_keys if key in archive),
                    None,
                )

                if selected_key is None:
                    if len(available_keys) == 1:
                        selected_key = available_keys[0]
                    else:
                        raise ValueError(
                            "The NPZ file contains multiple arrays and the image could not "
                            "be identified automatically. "
                            f"Path: {image_path} | keys: {available_keys}. "
                            "Use --npz-image-key to specify the correct key."
                        )

            return np.array(archive[selected_key], copy=True)

    except (OSError, ValueError, KeyError) as error:
        if isinstance(error, (ValueError, KeyError)):
            raise

        raise OSError(
            f"Could not open the NPZ file:\n{image_path}"
        ) from error


def read_npz(
    image_path: Path,
    image_key: str | None,
    apply_min_max_normalization: bool,
) -> torch.Tensor:
    """Read an NPZ file and return a float32 tensor of shape [1, H, W]."""

    image = load_npz_image_array(
        image_path=image_path,
        image_key=image_key,
    )
    image = np.asarray(image, dtype=np.float32)

    if image.ndim == 3:
        if image.shape[0] == 1:
            image = image[0]
        elif image.shape[-1] == 1:
            image = image[..., 0]
        else:
            raise ValueError(
                "The NPZ file has three dimensions but does not represent "
                "a single-channel image. "
                f"Path: {image_path} | shape: {image.shape}"
            )

    if image.ndim != 2:
        raise ValueError(
            "Expected an image with shape [H,W], [1,H,W], or [H,W,1]. "
            f"Path: {image_path} | shape: {image.shape}"
        )

    image = np.nan_to_num(
        image,
        nan=0.0,
        posinf=0.0,
        neginf=0.0,
    )

    image_min = float(image.min())
    image_max = float(image.max())

    if apply_min_max_normalization:
        if image_max > image_min:
            image = (image - image_min) / (image_max - image_min)
        else:
            image = np.zeros_like(image, dtype=np.float32)
    elif image_min < 0.0 or image_max > 1.0:
        raise ValueError(
            "Min-max normalization is disabled, but the image is not "
            "within the [0,1] range. "
            f"Path: {image_path} | min={image_min:.6f} | "
            f"max={image_max:.6f}"
        )

    image = np.ascontiguousarray(image, dtype=np.float32)
    return torch.from_numpy(image).unsqueeze(0)


class ResizeAndPad:
    """Preserve the aspect ratio and pad to output_size × output_size."""

    def __init__(self, output_size: int):
        self.output_size = int(output_size)

    def __call__(self, image: torch.Tensor) -> torch.Tensor:
        _, height, width = image.shape

        scale = self.output_size / max(height, width)
        new_height = max(1, round(height * scale))
        new_width = max(1, round(width * scale))

        image = F.interpolate(
            image.unsqueeze(0),
            size=(new_height, new_width),
            mode="bilinear",
            align_corners=False,
            antialias=True,
        ).squeeze(0)

        pad_height = self.output_size - new_height
        pad_width = self.output_size - new_width

        pad_top = pad_height // 2
        pad_bottom = pad_height - pad_top
        pad_left = pad_width // 2
        pad_right = pad_width - pad_left

        return F.pad(
            image,
            (pad_left, pad_right, pad_top, pad_bottom),
            value=0.0,
        )


class RepeatGrayscaleToRGB:
    """Convert [1,H,W] to [3,H,W] by repeating the channel."""

    def __call__(self, image: torch.Tensor) -> torch.Tensor:
        if image.ndim != 3 or image.shape[0] != 1:
            raise ValueError(
                "RepeatGrayscaleToRGB expected [1,H,W], but received "
                f"{tuple(image.shape)}."
            )

        return image.repeat(3, 1, 1)


def build_test_transform(
    image_size: int,
    imagenet_mean: list[float],
    imagenet_std: list[float],
):
    """Reproduce the training validation transform exactly."""

    return transforms.Compose([
        ResizeAndPad(image_size),
        RepeatGrayscaleToRGB(),
        transforms.Normalize(
            mean=imagenet_mean,
            std=imagenet_std,
        ),
    ])


