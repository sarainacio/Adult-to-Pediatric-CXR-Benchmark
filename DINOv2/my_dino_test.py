def json_safe(value: Any) -> Any:
    if isinstance(value, dict):
        return {key: json_safe(item) for key, item in value.items()}

    if isinstance(value, (list, tuple)):
        return [json_safe(item) for item in value]

    if isinstance(value, Path):
        return str(value)

    if isinstance(value, np.ndarray):
        return json_safe(value.tolist())

    if isinstance(value, np.integer):
        return int(value)

    if isinstance(value, (np.floating, float)):
        numeric_value = float(value)
        if math.isnan(numeric_value) or math.isinf(numeric_value):
            return None
        return numeric_value

    if isinstance(value, torch.Tensor):
        if value.numel() == 1:
            return json_safe(value.item())
        return json_safe(value.detach().cpu().tolist())

    return value


def save_predictions(
    output_path: Path,
    image_ids: list[str],
    targets: np.ndarray,
    probabilities: np.ndarray,
    predictions: np.ndarray,
    label_columns: list[str],
) -> None:
    data: dict[str, Any] = {"image_id": image_ids}

    for class_index, class_name in enumerate(label_columns):
        data[f"target__{class_name}"] = targets[:, class_index]
        data[f"probability__{class_name}"] = probabilities[:, class_index]
        data[f"prediction__{class_name}"] = predictions[:, class_index]

    pd.DataFrame(data).to_csv(output_path, index=False)


def format_metric(value: Any) -> str:
    if value is None:
        return "N/A"

    try:
        numeric_value = float(value)
    except (TypeError, ValueError):
        return str(value)

    if not math.isfinite(numeric_value):
        return "N/A"

    return f"{numeric_value:.6f}"


def print_summary(summary: dict[str, Any]) -> None:
    print("\n" + "=" * 70)
    print("OVERALL TEST SET RESULTS")
    print("=" * 70)

    preferred_order = [
        "number_of_images",
        "number_of_classes",
        "classification_threshold",
        "mAP",
        "micro_AP",
        "macro_AUROC",
        "macro_sensitivity",
        "macro_specificity",
        "macro_F1",
        "micro_F1",
    ]

    for key in preferred_order:
        value = summary[key]
        if isinstance(value, (int, np.integer)):
            formatted = str(value)
        else:
            formatted = format_metric(value)
        print(f"{key}: {formatted}")


